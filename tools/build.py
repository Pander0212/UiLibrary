#!/usr/bin/env python3
"""
build.py - bundles src/**/*.lua into dist/NovaUI.lua (single loadstring-able file).

Every module becomes a function in a module table; modules load each other lazily
through `Import("Path/Name")` (path relative to src, without extension). The bundle
returns `Import("init")`.

Usage:
    python3 tools/build.py            # build
    python3 tools/build.py --check    # build + run tools/luau_check.py on the bundle
"""
import os
import re
import subprocess
import sys
from datetime import datetime, timezone

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "src")
DIST = os.path.join(ROOT, "dist")
OUT = os.path.join(DIST, "NovaUI.lua")


def read_constant(name):
    with open(os.path.join(SRC, "Constants.lua"), encoding="utf-8") as fh:
        m = re.search(name + r'\s*=\s*"([^"]+)"', fh.read())
    return m.group(1) if m else "?"


def collect_modules():
    modules = []
    for base, _, files in os.walk(SRC):
        for f in sorted(files):
            if not f.endswith(".lua"):
                continue
            path = os.path.join(base, f)
            name = os.path.relpath(path, SRC)[:-4].replace(os.sep, "/")
            modules.append((name, path))
    modules.sort(key=lambda m: (m[0] == "init", m[0]))
    return modules


def strip_directives(source):
    # `--!strict` style directives are only valid at the top of a file
    return "\n".join(line for line in source.splitlines() if not line.startswith("--!"))


def indent(source):
    return "\n".join(("\t" + line) if line.strip() else "" for line in source.splitlines())


def build():
    modules = collect_modules()
    name = read_constant("Name")
    version = read_constant("Version")
    stamp = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    parts = [
        f"--[[\n\t{name} v{version}\n\tBundled build - generated by tools/build.py ({stamp}).\n"
        f"\tDo not edit this file directly: change src/ and rebuild.\n\n"
        f"\tUsage: local UI = loadstring(game:HttpGet(\"<raw url>/dist/NovaUI.lua\"))()\n]]\n",
        "local __modules: { [string]: () -> any } = {}",
        "local __cache: { [string]: any } = {}",
        "local __loading: { [string]: boolean } = {}",
        "",
        "local function Import(name: string): any",
        "\tlocal cached = __cache[name]",
        "\tif cached ~= nil then",
        "\t\treturn cached",
        "\tend",
        "\tlocal loader = __modules[name]",
        "\tif not loader then",
        "\t\terror(\"[NovaUI] unknown module '\" .. tostring(name) .. \"'\", 2)",
        "\tend",
        "\tif __loading[name] then",
        "\t\terror(\"[NovaUI] circular import of '\" .. name .. \"' - use a lazy Import inside a function\", 2)",
        "\tend",
        "\t__loading[name] = true",
        "\tlocal result = loader()",
        "\t__loading[name] = nil",
        "\t__cache[name] = if result == nil then true else result",
        "\treturn __cache[name]",
        "end",
        "",
    ]
    for mod_name, path in modules:
        with open(path, encoding="utf-8") as fh:
            source = strip_directives(fh.read()).rstrip()
        parts.append(f"-- {'=' * 74}\n-- {mod_name}\n-- {'=' * 74}")
        parts.append(f'__modules["{mod_name}"] = function()')
        parts.append(source)  # not re-indented: keeps long strings byte-identical
        parts.append("end\n")
    parts.append('return Import("init")\n')
    os.makedirs(DIST, exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(parts))
    size = os.path.getsize(OUT)
    print(f"built {os.path.relpath(OUT, ROOT)}: {len(modules)} modules, {size / 1024:.1f} KiB")
    return OUT


if __name__ == "__main__":
    out = build()
    if "--check" in sys.argv:
        checker = os.path.join(ROOT, "tools", "luau_check.py")
        sys.exit(subprocess.call([sys.executable, checker, out]))
